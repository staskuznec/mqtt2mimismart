-- Переключение элемента нажатием в приложении.
--
-- Устройство зажигает элемент и не гасит: датчик протечки на батарейках спит,
-- воду вытерли, а «протечка» горит до его следующего пробуждения. Снять её
-- было нечем — виртуальный элемент по нажатию сам не меняется, статус ему
-- обязан прислать тот, кто его ведёт. Раньше это делал скрипт умного дома,
-- теперь может шлюз.
ALTER TABLE links ADD COLUMN toggle_on_press INTEGER NOT NULL DEFAULT 0;
