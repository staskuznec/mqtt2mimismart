-- Пары связок.
--
-- Двусторонняя привязка — это всё равно две связки: у направлений разные поля,
-- разные счётчики и своё включение, и когда команда не уходит, а состояние
-- приходит, это должно быть видно раздельно.
--
-- Но заводиться и удаляться они должны вместе, иначе получается половина
-- привязки: элемент показывает состояние, но не управляет, — и понять это
-- можно только опытным путём.
ALTER TABLE links ADD COLUMN pair_id INTEGER;

CREATE INDEX links_pair ON links (pair_id);
