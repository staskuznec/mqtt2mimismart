-- Топики, которые снифер больше не запоминает.
--
-- Шлюз подписан на всю шину, и на объекте с чужими устройствами страница
-- «Топики» тонет в том, что к умному дому отношения не имеет. Убрать такой
-- топик из памяти мало: он вернётся со следующим же сообщением, а чужой датчик
-- публикует каждые несколько секунд. Поэтому список лежит в базе — снифер
-- спрашивает его на каждом сообщении, и переживает перезапуск: за ночь чужое
-- устройство с шины никуда не денется.
CREATE TABLE hidden_topics (
    pattern    TEXT PRIMARY KEY,
    -- 1 — скрыт мастер-топик целиком, со всем, что лежит под ним.
    whole_tree INTEGER NOT NULL DEFAULT 0,
    created_at INTEGER NOT NULL
);
