-- Назначение исходящей связки.
--
-- У направления «умный дом → шина» два разных смысла, и путать их опасно.
--
-- command — команда устройству. Сохранённая команда недопустима: брокер отдаст
-- её устройству при следующем подключении, и реле щёлкнет само.
--
-- state — показание наружу, для панелей и сторонних систем. Здесь сохранённое
-- значение как раз нужно: без него новый подписчик висит с пустотой до
-- следующего изменения, а датчик может не меняться часами.
--
-- Для входящих связок поле не используется.
ALTER TABLE links ADD COLUMN kind TEXT NOT NULL DEFAULT 'command';
